# Writes web/src/fx/particles/functions/vecnoise_tables.js: the lattice tables of particles.dll's gradient-table noise
# FUN_180368850 (C_OP_CurlNoiseForce's CURL potential). Read-only on the DLL.
#   python tools/particles/vecnoise-tables.py <particles.dll> <out.js>
# Three permutation tables of 256 int32 (rva 0x46aa90 x, 0x46ae90 y, 0x46b290 z) and 256 float32 vec3 (rva 0x469e90).
import sys, struct, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pe import PE
p = PE(sys.argv[1])
perms = []
for rva in (0x46aa90, 0x46ae90, 0x46b290):
    t = struct.unpack('<256i', p.read(rva, 1024))
    assert sorted(t) == list(range(256)), hex(rva)
    perms.append(bytes(t).hex())
g = p.read(0x469e90, 256 * 12)
gh = g.hex()  # little-endian float32 bytes
def chunk(s, n=112): return [s[i:i + n] for i in range(0, len(s), n)]
out = ['// Generated by tools/particles/vecnoise-tables.py from particles.dll md5 63babcbf3245e56855a777134323e74a. Do not edit.',
       '// The lattice tables of the gradient-table noise FUN_180368850: permutations (one byte per entry, the DLL stores',
       '// int32 0..255) at rva 0x46aa90 (x), 0x46ae90 (y), 0x46b290 (z); 256 unit vectors (float32 x, y, z, little-endian',
       '// bytes) at rva 0x469e90.']
for name, h in zip(('PERM_X', 'PERM_Y', 'PERM_Z'), perms):
    out.append(f'export const {name} = Uint8Array.from(("' + '" +\n  "'.join(chunk(h)) + '").match(/../g), (b) => parseInt(b, 16));')
out.append('export const VECTORS = new Float32Array(Uint8Array.from(("' + '" +\n  "'.join(chunk(gh)) + '").match(/../g), (b) => parseInt(b, 16)).buffer);')
open(sys.argv[2], 'w', newline='\n').write('\n'.join(out) + '\n')
