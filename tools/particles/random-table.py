"""Write the particle random table (particles.dll DAT_180598f60: 4,096 float32 in [0, 1); the dword before is 4, a pointer follows) as
web/src/fx/particles/functions/random_table.js, base64 of the raw little-endian floats.

    python tools/particles/random-table.py <particles.dll> [out.js]

Read from md5 63babcbf3245e56855a777134323e74a; another build may move the table (find it in a decompile: the
`& 0xfff` index into a float array of every CONSTANT / VARYING draw).
"""
import base64, hashlib, os, struct, sys
from pe import PE

ADDR = 0x180598f60
dll = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), '../../web/src/fx/particles/functions/random_table.js')
p = PE(dll)
off = p.rva2off(ADDR - p.base)
raw = p.data[off:off + 4 * 4096]
t = struct.unpack('<4096f', raw)
assert all(0 <= x < 1 for x in t), 'not the random table at this address'
md5 = hashlib.md5(open(dll, 'rb').read()).hexdigest()
b64 = base64.b64encode(raw).decode()
lines = [b64[i:i + 116] for i in range(0, len(b64), 116)]
with open(out, 'w', newline='\n') as f:
    f.write('// Generated by tools/particles/random-table.py: the particle random table, particles.dll md5 %s DAT_%x\n' % (md5, ADDR))
    f.write('// (4,096 float32, little-endian, base64). Every CONSTANT / VARYING draw indexes it & 0xfff (RE section 11).\n')
    f.write('const B64 =\n')
    f.write('\n'.join("  '%s'%s" % (l, ' +' if i < len(lines) - 1 else ';') for i, l in enumerate(lines)))
    f.write('\n\nconst bin = typeof atob === \'function\' ? atob(B64) : Buffer.from(B64, \'base64\').toString(\'binary\');\n')
    f.write('const bytes = new Uint8Array(bin.length);\n')
    f.write('for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);\n')
    f.write('export const RANDOM_TABLE = new Float32Array(bytes.buffer);\n')
print('wrote', out, len(t), 'floats')
