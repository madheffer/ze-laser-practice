#!/usr/bin/env node
// Particle class defaults for the runtime (web/src/fx/particles/defaults.js), from CS2's own particles.dll.
//
// A compiled .vpcf leaves out every field equal to its class default, so the runtime needs each class's defaults to
// read a file the way the game does. particles.dll serialises them itself: every concrete class has an
// MGetKV3ClassDefaults function that default-constructs the class and writes it as KV3.
//
//   cd <scratch> && set CS2_GAME_DIR=<CS2>/game
//   python tools/particles/schemadump.py   ->  schema_raw.json  (every class / enum record)
//   python tools/particles/kv3all.py       ->  kv3_defaults.json (each class's MGetKV3ClassDefaults, as JSON)
//   node tools/particles/defaults.mjs <scratch dir>   (rewrites web/src/fx/particles/defaults.js)
//
// Classes are written whole (the runtime's expandDefaults reads an object without "$" / "$base" as is); structs,
// bases and the array-element table already in defaults.js are kept and extended; enums come from the schema.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';

const dir = process.argv[2];
if (!dir) { console.error('usage: defaults.mjs <dir with schema_raw.json + kv3_defaults.json>'); process.exit(2); }
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const out = path.join(root, 'web/src/fx/particles/defaults.js');
const schema = JSON.parse(fs.readFileSync(path.join(dir, 'schema_raw.json'), 'utf8'));
const kv3 = JSON.parse(fs.readFileSync(path.join(dir, 'kv3_defaults.json'), 'utf8'));
const prev = (await import(pathToFileURL(out).href)).default;

const classes = { ...prev.classes };
let added = 0;
for (const [cls, rec] of Object.entries(kv3)) {
  if (!rec.json) continue;
  const v = JSON.parse(rec.json);
  delete v._class;
  if (!prev.classes[cls]) added++;
  classes[cls] = v;
}

// enums: { name: { value: enumerator } }
const enums = { ...prev.enums };
for (const [name, e] of Object.entries(schema.enums || {})) {
  const byValue = {};
  for (const x of e.enumerators || e.values || []) if (x && x.name != null) byValue[String(x.value)] = x.name;
  if (Object.keys(byValue).length) enums[name] = byValue;
}

// array fields whose elements are a known struct: { fieldName: struct }
const elements = { ...prev.elements };
const structs = { ...prev.structs };
for (const c of Object.values(schema.classes || {})) {
  for (const f of c.fields || []) {
    const m = /CUtlVector<\s*([A-Za-z_]\w*)\s*>/.exec(f.type || '');
    if (m && (structs[m[1]] || kv3[m[1]]?.json) && !elements[f.name]) elements[f.name] = m[1];
  }
}
for (const [name, rec] of Object.entries(kv3)) if (rec.json && !classes[name]?.m_flOpStrength && /_t$|Input$|Parameters$/.test(name) && !structs[name]) {
  const v = JSON.parse(rec.json); delete v._class; structs[name] = v;
}

const dll = path.join(process.env.CS2_GAME_DIR || '', 'bin/win64/particles.dll');
const md5 = fs.existsSync(dll) ? crypto.createHash('md5').update(fs.readFileSync(dll)).digest('hex') : 'unknown';
const doc = {
  source: { method: 'MGetKV3ClassDefaults of each class, default-constructed and serialized by particles.dll', builds: { 'particles.dll': md5 }, generator: 'tools/particles/defaults.mjs' },
  structs, elements, bases: prev.bases, classes, enums,
};
fs.writeFileSync(out, '/* eslint-disable */\n// Generated by tools/particles/defaults.mjs from particles.dll (MGetKV3ClassDefaults). Do not edit.\nexport default ' + JSON.stringify(doc) + ';\n');
console.log(`defaults.js: ${Object.keys(classes).length} classes (+${added}), ${Object.keys(enums).length} enums, ${Object.keys(elements).length} array element types, particles.dll ${md5}`);
