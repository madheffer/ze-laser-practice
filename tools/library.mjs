#!/usr/bin/env node
// Turn a library scan (lasers-bake --scan) + GFL's EntWatch configs into MAPS.md: the local workshop maps ranked as
// laser-practice candidates, with each one's GFL items / heal, and whether it's baked / has stages here.
//
//   lasers-bake --scan D:/Steam/steamapps/workshop/content/730 library.json
//   node tools/library.mjs library.json [entwatch dir of <map>.jsonc]  > MAPS.md
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const [scanFile, ewDir] = process.argv.slice(2);
if (!scanFile) { console.error('usage: library.mjs <scan.json> [entwatch dir]'); process.exit(2); }
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const scan = JSON.parse(fs.readFileSync(scanFile, 'utf8'));
const HEAL = /heal|cure|regen|medic|recover|restor|potion/i;
const ZM = /^(zombie|zm)\b|\bzm\b|zombie/i;
const ew = (map) => {
  const f = ewDir && ['.jsonc', '.json'].map((x) => path.join(ewDir, map + x)).find((p) => fs.existsSync(p));
  if (!f) return null;
  try { return JSON.parse(fs.readFileSync(f, 'utf8').replace(/^\s*\/\/.*$/gm, '').replace(/,(\s*[\]}])/g, '$1')); } catch { return null; }
};
const baked = (m) => fs.existsSync(path.join(root, 'web/public/maps', m, 'manifest.json'));
const stages = (m) => { try { return JSON.parse(fs.readFileSync(path.join(root, 'web/public/scenarios', `${m}.json`), 'utf8')).scenarios.length; } catch { return 0; } };
const WANTED = ['ze_offliner', 'ze_visualizer', 'ze_neochrome', 'ze_arcana_heart', 'ze_ffvii_mako_reactor_v5_p', 'ze_ffvii_mako_reactor_v6_p', 'ze_dreamin'];

const rows = scan.filter((r) => r.score > 0).sort((a, b) => b.score - a.score).map((r) => {
  const items = ew(r.map);
  const human = (items || []).filter((i) => i?.name && !ZM.test(i.name) && !ZM.test(i.shortname || ''));
  return { ...r, gfl: !!items, items: human.map((i) => i.shortname || i.name), heals: human.filter((i) => HEAL.test(i.name)).map((i) => i.shortname || i.name) };
});
const line = (r) => `| ${WANTED.includes(r.map) ? '**' + r.map + '**' : r.map} | ${r.score} | ${r.laserTemplates} | ${r.laserNamed} | ${r.bosses} | ${r.gfl ? 'yes' : '-'} | ${r.heals.join(', ') || '-'} | ${r.items.filter((i) => !r.heals.includes(i)).join(', ') || '-'} | ${baked(r.map) ? (stages(r.map) ? `${stages(r.map)} stages` : 'baked') : r.item} |`;
const head = '| map | score | laser templates | "laser" names | boss ents | on GFL | heal item | other human items | here / workshop id |\n|---|---|---|---|---|---|---|---|---|';
const missing = WANTED.filter((m) => !scan.some((r) => r.map === m));

console.log(`# Map candidates

Generated by \`tools/library.mjs\` from a scan of the local workshop library (\`lasers-bake --scan\`, ${scan.length} maps, ${new Date().toISOString().slice(0, 10)}) and GFL's EntWatch configs (github.com/gflze/CS2-ZE-Configs). Pick maps here; ROADMAP.md tracks the chosen ones.

**score** = 3 x laser templates + "laser"-named entities (max 60) + boss entities (max 20). A *laser template* is a template lump with a trigger_hurt on a mover (door / movelinear / train / rotator): every laser wave traced so far (mist, westersand, deadcore) is one. **heal item** = a human EntWatch item named like a heal (the game also checks the map's data: world/items.js). Requested maps are **bold**.${missing.length ? `\n\nRequested but not in the local library: ${missing.join(', ')} (subscribe in the workshop, then rescan).` : ''}

## Requested
${head}
${rows.filter((r) => WANTED.includes(r.map)).map(line).join('\n')}

## All laser candidates (score > 0)
${head}
${rows.map(line).join('\n')}

${scan.length - rows.length} more maps scored 0 (no laser shapes in their entity data).`);
