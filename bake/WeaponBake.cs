    public static int Run(string pak01, string outFile)
    {
        var pkg = new Package();
        pkg.Read(pak01);
        var table = Read(pkg);
        var json = table.ToJsonString(new JsonSerializerOptions { WriteIndented = true });
        json = System.Text.RegularExpressions.Regex.Replace(json, @"\[\s+([-\d.]+),\s+(""[^""]*"")\s+\]", "[$1, $2]"); // one [t, sound] a line
        var sb = new StringBuilder();
        sb.Append("// GENERATED by `lasers-bake --weapons` (bake/WeaponBake.cs) from CS2's scripts/weapons.vdata and the viewmodel\n");
        sb.Append("// draw / reload clips (their sound events, seconds). Don't edit: rebake. Read through lib/weapons.js.\n");
        sb.Append("export const CS2_GUNS = ").Append(json).Append(";\n");
        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(outFile))!);
        File.WriteAllText(outFile, sb.ToString().Replace("\r\n", "\n"));
        Console.WriteLine($"weapons: {table.Count} guns -> {outFile}");
        return 0;
    }

    /// Every sound event the guns name (shots, draws, reloads), for the stock sound set.
    public static IEnumerable<string> SoundNames(Package pkg)
    {
        foreach (var (_, g) in Read(pkg))
        {
            yield return g!["fireSound"]!.GetValue<string>();
            foreach (var key in new[] { "drawSounds", "reloadSounds" })
                foreach (var s in g[key]!.AsArray()) yield return s![1]!.GetValue<string>();
        }
    }

    static JsonObject Read(Package pkg)
    {
        var vdata = Decode(pkg, "scripts/weapons.vdata_c") ?? throw new InvalidOperationException("scripts/weapons.vdata_c not in pak01");
        var blocks = new Dictionary<string, KVObject>(StringComparer.OrdinalIgnoreCase);
        foreach (var (k, v) in vdata.Children) if (k != null && v.IsCollection) blocks[k] = v;
        var table = new JsonObject();
        foreach (var (name, chassis, dir, suffix) in Guns)
        {
            if (!blocks.ContainsKey(name)) { Console.WriteLine($"weapons: {name} not in weapons.vdata"); continue; }
            KVObject? Get(string key)
            {
                // a weapon's own field, else its _base chain's (weapon_base at the root)
                var seen = 0;
                for (var b = blocks[name]; b != null && seen++ < 8;)
                {
                    if (b.TryGetValue(key, out var v)) return v;
                    b = b.TryGetValue("_base", out var bn) && blocks.TryGetValue(Str(bn), out var next) ? next : null;
                }
                return null;
            }
            double N(string key) { var v = Get(key); return v == null ? 0 : v.IsArray ? Num(v[0]) : Num(v); }
            bool B(string key) => N(key) != 0;
            var clip = (int)N("m_iMaxClip1");
            var reserve = (int)N("m_nPrimaryReserveAmmoMax");
            if (B("m_bReserveAmmoAsClips")) reserve *= clip;
            // a silenced gun (M4A1-S detachable, MP5-SD integrated) comes with it on: CS2 plays WEAPON_SOUND_SPECIAL1
            var sounds = Get("m_aShootSounds");
            var silenced = Str(Get("m_eSilencerType")) != "WEAPONSILENCER_NONE";
            var fire = silenced && sounds != null && sounds.TryGetValue("WEAPON_SOUND_SPECIAL1", out var sp) ? Str(sp)
                : sounds != null && sounds.TryGetValue("WEAPON_SOUND_SINGLE", out var single) ? Str(single) : "";
            var clips = $"animation/anims/viewmodel/rifle/{dir}/";
            table[name] = new JsonObject
            {
                ["chassis"] = chassis,
                ["damage"] = (int)N("m_nDamage"),
                ["cycle"] = R(N("m_flCycleTime")),
                ["clip"] = clip,
                ["reserve"] = reserve,
                ["deploy"] = R(N("m_flDeployDuration")),
                ["fullAuto"] = B("m_bIsFullAuto"),
                ["burstMode"] = B("m_bHasBurstMode"),
                ["range"] = R(N("m_flRange")),
                ["bullets"] = (int)N("m_nNumBullets"),
                ["maxSpeed"] = R(N("m_flMaxSpeed")),
                ["reload"] = R(N("m_flDisallowAttackAfterReloadStartDuration")),
                ["price"] = (int)N("m_nPrice"),
                // the recoil pattern's inputs (primary mode, [0]): m_flRecoilAngle / AngleVariance / Magnitude /
                // MagnitudeVariance and m_nRecoilSeed. lib/recoil.js turns them into the kick.
                ["recoil"] = new JsonObject
                {
                    ["angle"] = R(N("m_flRecoilAngle")),
                    ["angleVariance"] = R(N("m_flRecoilAngleVariance")),
                    ["magnitude"] = R(N("m_flRecoilMagnitude")),
                    ["magnitudeVariance"] = R(N("m_flRecoilMagnitudeVariance")),
                    ["seed"] = (int)N("m_nRecoilSeed"),
                },
                ["fireSound"] = fire,
                ["drawSounds"] = ClipSounds(pkg, $"{clips}draw_{suffix}.vnmclip_c"),
                ["reloadSounds"] = ClipSounds(pkg, $"{clips}reload_{suffix}.vnmclip_c"),
            };
        }
        return table;
    }

    // A clip's CNmSoundEvents as [seconds, event name]: m_flStartTime is a fraction of the clip's m_flDuration.
    static JsonArray ClipSounds(Package pkg, string path)
    {
        var list = new JsonArray();
        var clip = Decode(pkg, path);
        if (clip == null) { Console.WriteLine($"weapons: {path} not in pak01"); return list; }
        var duration = clip.TryGetValue("m_flDuration", out var d) ? Num(d) : 0;
        if (!clip.TryGetValue("m_events", out var events) || !events.IsArray) return list;
        foreach (var ev in events.Values)
        {
            if (!ev.IsCollection || !ev.TryGetValue("_class", out var cls) || Str(cls) != "CNmSoundEvent") continue;
            if (!ev.TryGetValue("m_name", out var n) || Str(n).Length == 0) continue;
            var start = ev.TryGetValue("m_flStartTime", out var st) && st.IsCollection && st.TryGetValue("m_flValue", out var fv) ? Num(fv) : 0;
            list.Add(new JsonArray(R(start * duration), Str(n)));
        }
        return list;
    }

    static KVObject? Decode(Package pkg, string path)
    {
        var e = pkg.FindEntry(path);
        if (e == null) return null;
        pkg.ReadEntry(e, out var bytes);
        using var res = new Resource { FileName = path };
        res.Read(new MemoryStream(bytes));
        return res.DataBlock is BinaryKV3 kv ? kv.Data : null;
    }

    static string Str(KVObject? v) => v?.ToString(CultureInfo.InvariantCulture) ?? "";
    static double Num(KVObject v) => v.ValueType switch
    {
        KVValueType.Boolean => v.ToBoolean(CultureInfo.InvariantCulture) ? 1 : 0,
        KVValueType.String => double.TryParse(Str(v), NumberStyles.Float, CultureInfo.InvariantCulture, out var x) ? x : 0,
        _ => v.ToDouble(CultureInfo.InvariantCulture),
    };
    static double R(double v) => Math.Round(v, 4);
}
