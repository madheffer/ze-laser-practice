// lasers-bake --weapons <web/src/lib/weapons-cs2.js> [--cs2 <game/csgo>]: the guns a ZE human can buy, with CS2's own
// numbers. Per gun: scripts/weapons.vdata (damage, cycle, clip, reserve, deploy, full-auto, range, speed, the reload's
// attack lock, price, the shot sound) and the viewmodel's draw / reload clips (their CNmSoundEvents: what plays when,
// in seconds). Written as an ES module both the game and the co-op server import (web/src/lib/weapons.js).
// SoundBake.Stock exports every sound named here (lasers-bake --stock-sounds), and PanoramaBake the HUD icons.
using System.Globalization;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;
using SteamDatabase.ValvePak;
using ValveKeyValue;
using ValveResourceFormat;
using ValveResourceFormat.ResourceTypes;

namespace Lasers.Bake;

static class WeaponBake
{
    // vdata name, the viewmodel chassis (web/public/weapons/fp/classes/<chassis>), its clip folder and clip suffix.
    // Shotguns are left out: Nova / XM1014 / Sawed-Off reload shell by shell and every shotgun fires pellets.
    public static readonly (string Vdata, string Chassis, string Dir, string Suffix)[] Guns =
    [
