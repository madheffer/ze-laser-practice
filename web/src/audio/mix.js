// CS2's sound mixer, as far as a voice's volume and reverb send go (soundsystem.dll snd_mixgroups.cpp): the
// csgo_mega / csgo_music stacks multiply every voice by its mix group's level (soundmixer_get_mixgroup
// @public.mixgroup -> mult_mixer_volume) and scale its reverb send by the group's dsp value (@mixer.output_dsp).
// A group's level is its Default_Mix vol times its mix-layer factor (audio/layers.js) times its parent's level, up to
// the root (FUN_180034870 recurses on the parent); dsp the same with the dsp column. A group soundmixers.txt doesn't
// define (csgo_mega's default "Dialog") leaves the voice at 1, as the operator returns without writing its outputs.
// Numbers: lib/sound-mix-cs2.js, generated by `lasers-bake --mixers`.
import { MIX_LEVELS, MIX_PARENTS, MIX_DSP } from '../lib/sound-mix-cs2.js';

const DEFAULT_GROUP = { csgo_mega: 'Dialog', csgo_music: 'Music' }; // each stack's public mixgroup default
const NAMES = new Map(Object.keys(MIX_PARENTS).concat(Object.keys(MIX_LEVELS)).map((g) => [g.toLowerCase(), g]));
const find = (n) => NAMES.get(String(n || '').toLowerCase()) || null;

// A sound event's mix group name, as soundsmixers.txt spells it (null when undefined there).
export const eventGroup = (def) => find(def?.mixgroup ?? DEFAULT_GROUP[def?.type] ?? '');

// { vol, dsp } for mix group `group` (exact name or null), with each group's layer factor from factorOf(group).
export function groupLevels(group, factorOf = null) {
  let g = group, vol = 1, dsp = 1;
  for (let guard = 0; g && guard < 16; guard++) {
    const v = MIX_LEVELS[g];
    if (v == null || v < 0) break; // no level in Default_Mix: the voice keeps what it has
    vol *= v * (factorOf ? factorOf(g) : 1);
    dsp *= MIX_DSP[g] ?? 1;
    g = MIX_PARENTS[g] ? find(MIX_PARENTS[g]) : null;
  }
  return { vol, dsp };
}

// The level of mix group `name` in Default_Mix (no layers), case-insensitive; 1 for an unknown group.
export const mixGroupLevel = (name) => groupLevels(find(name)).vol;

// A sound event's mixer level (no layers): its own mixgroup, else its stack's default.
export const mixVolume = (def) => groupLevels(eventGroup(def)).vol;

// csgo_mega's volume_random_add: volume + a uniform pick in [volume_random_min, volume_random_max], multiplied into the
// voice as it is (volume_volume_linear_mult x 1, no clamp): Valve's dust.Indoors.Rocks is volume 0 with -0.85..-0.6, a
// polarity-inverted voice at 0.6-0.85. Its magnitude is what you hear.
export function eventVolume(def) {
  const v = def?.volume ?? 1;
  const r = def?.volumeRandom;
  return Math.abs(r ? v + r[0] + Math.random() * (r[1] - r[0]) : v);
}

// [[x, y], ...] at x, linear between points, flat past the ends (time / fade curves)
export function curveAt(curve, x) {
  if (!Array.isArray(curve) || !curve.length) return 1;
  if (x <= curve[0][0]) return curve[0][1];
  for (let i = 1; i < curve.length; i++) {
    const [x1, y1] = curve[i];
    if (x <= x1) { const [x0, y0] = curve[i - 1]; return x1 > x0 ? y0 + (y1 - y0) * (x - x0) / (x1 - x0) : y1; }
  }
  return curve[curve.length - 1][1];
}
