// CS2's sound mixer, as far as a voice's volume goes (soundsystem.dll snd_mixgroups.cpp): the csgo_mega / csgo_music
// stacks multiply every voice by its mix group's level (soundmixer_get_mixgroup @public.mixgroup -> mult_mixer_volume),
// and a group's level is its Default_Mix vol times its parent's, up to the root (FUN_180034870 recurses on the
// parent). A group soundmixers.txt doesn't define (csgo_mega's default "Dialog") leaves the voice at 1, as the operator
// returns without writing its outputs. Mix layers, ducking and triggers (other mixers) aren't modelled: they sit at 1
// in Default_Mix. Numbers: lib/sound-mix-cs2.js, generated by `lasers-bake --mixers`.
import { MIX_LEVELS, MIX_PARENTS } from '../lib/sound-mix-cs2.js';

const DEFAULT_GROUP = { csgo_mega: 'Dialog', csgo_music: 'Music' }; // each stack's public mixgroup default
const cache = new Map();

// The level of mix group `name` (case-insensitive, as soundsystem's V_stricmp lookup); 1 for an unknown group.
export function mixGroupLevel(name) {
  const key = String(name || '').toLowerCase();
  if (cache.has(key)) return cache.get(key);
  const groups = Object.keys(MIX_PARENTS).concat(Object.keys(MIX_LEVELS));
  const find = (n) => groups.find((g) => g.toLowerCase() === String(n).toLowerCase());
  let g = find(key), level = 1;
  for (let guard = 0; g && guard < 16; guard++) {
    const vol = MIX_LEVELS[g];
    if (vol == null || vol < 0) break; // no level in Default_Mix: the voice keeps what it has
    level *= vol;
    g = MIX_PARENTS[g] ? find(MIX_PARENTS[g]) : null;
  }
  cache.set(key, level);
  return level;
}

// A sound event's mixer level: its own mixgroup, else its stack's default.
export const mixVolume = (def) => mixGroupLevel(def?.mixgroup ?? DEFAULT_GROUP[def?.type] ?? '');

// csgo_mega's volume_random_add: volume + a uniform pick in [volume_random_min, volume_random_max], never below 0.
export function eventVolume(def) {
  const v = def?.volume ?? 1;
  const r = def?.volumeRandom;
  return Math.max(0, r ? v + r[0] + Math.random() * (r[1] - r[0]) : v);
}
